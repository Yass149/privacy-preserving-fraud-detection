"""Load the PaySim synthetic mobile-money dataset into GPU memory.

PaySim is the dissertation's second dataset, used to test whether the
DP-SGD-under-class-imbalance finding generalises beyond Elliptic. It is
structurally unlike Elliptic in every relevant way: ~140x larger (6,362,620
rows), fraud ~76x rarer, tabular rather than graph-derived.

Two functions, differing in whether the time column survives:
  load_paysim_data()            - features and labels only.
  load_paysim_data_with_time()  - also returns the 'step' column separately, so
                                  train_paysim.py can build a chronological
                                  (leakage-free) train/test split. Captured
                                  BEFORE one-hot encoding, since get_dummies
                                  may reorder columns and positional indexing
                                  into the result is not safe.

Labels come from PaySim's `isFraud` column, which the simulator sets on
transactions generated by its scripted account-takeover fraud agents. The
separate `isFlaggedFraud` column -- the output of a naive built-in rule, not
ground truth -- is dropped and never used as a training target.

On row ordering: rows are sorted by step with the source CSV order as
tiebreaker, giving a total, reproducible order. Unlike Elliptic, PaySim is
structurally immune to the windowing-leakage problem documented in
data_loader.py, because train_paysim.py uses window_size=1 -- a window is a
single transaction, so its composition cannot depend on its neighbours. The
sort here is for reproducibility and to future-proof a larger window size.
"""

import cudf
import torch
import time


def load_paysim_data(csv_path):
    """Zero-copy GPU load for the raw scalability benchmark (Section 6.1) --
    returns features/labels only, no step column. Kept separate from
    load_paysim_data_with_time() below so the existing scalability benchmark
    script doesn't change behavior."""
    print(f"--- Initiating PaySim Big Data Pipeline ---")
    start_time = time.time()

    print(f"Loading records from {csv_path} using NVIDIA cuDF...")
    df = cudf.read_csv(csv_path)

    load_time = time.time() - start_time
    print(f"Successfully loaded {len(df)} rows into VRAM in {load_time:.2f} seconds.")

    print("Encoding categorical variables and dropping non-numeric IDs...")
    df = df.drop(columns=['nameOrig', 'nameDest', 'isFlaggedFraud'])
    df = cudf.get_dummies(df, columns=['type'])

    feature_cols = [col for col in df.columns if col != 'isFraud']
    features_df = df[feature_cols]
    labels_df = df['isFraud']

    print("Executing Zero-Copy transfer to PyTorch...")
    features_tensor = torch.as_tensor(features_df.to_cupy(), device='cuda', dtype=torch.float32)
    labels_tensor = torch.as_tensor(labels_df.to_cupy(), device='cuda', dtype=torch.long)

    print(f"Final Features Tensor Shape: {features_tensor.shape}")
    print(f"Final Labels Tensor Shape: {labels_tensor.shape}")

    total_time = time.time() - start_time
    print(f"--- Pipeline Complete in {total_time:.2f} seconds ---")

    return features_tensor, labels_tensor


def load_paysim_data_with_time(csv_path):
    """
    Like load_paysim_data(), but explicitly captures the 'step' column
    (PaySim's hour-of-simulation field, 1-744) BEFORE any column dropping
    or one-hot encoding, and returns it as its own tensor rather than
    relying on its position surviving get_dummies() (which is not
    guaranteed -- dummy columns can be inserted/reordered depending on the
    cuDF version). Used by train_paysim.py to build a correct chronological
    (leakage-free) train/test split, mirroring how time_step is handled for
    Elliptic in data_loader.py.
    """
    print(f"Loading PaySim data from {csv_path} (with explicit time column)...")
    df = cudf.read_csv(csv_path)

    # Sort by step before anything downstream relies on row order. This mirrors
    # data_loader.py's sort for Elliptic: if PaySim's window_size is ever raised
    # above 1, unsorted rows would let sliding windows group temporally
    # unrelated transactions -- the exact bug class documented in
    # thesis_source.md Section 3.6.
    #
    # NOTE on the ordering-contamination issue found in Elliptic (see
    # data_loader.py's `tiebreak` docs): PaySim is structurally immune to it.
    # train_paysim.py uses window_size=1, so each "window" is a single row and
    # window composition cannot depend on neighbouring rows at all. Row order
    # here affects only DataLoader batching, which is shuffled anyway. The sort
    # below is therefore purely for reproducibility and for future-proofing
    # against window_size ever being raised.
    #
    # As with Elliptic, the sort must be TOTAL to be deterministic. PaySim's
    # 'step' field takes only 744 distinct values across 6.36M rows, so ties are
    # enormous (~8.5k rows per step), and an unstable ordering of those ties
    # varies run to run. PaySim has no unique key column (nameOrig/nameDest
    # repeat), so the CSV's own row order is captured as an explicit column and
    # used as the tiebreaker -- giving a total order that is identical on every
    # run of the same input file.
    df = df.reset_index(drop=True)
    df["_source_row"] = df.index
    df = df.sort_values(["step", "_source_row"]).reset_index(drop=True)
    df = df.drop(columns=["_source_row"])

    step_series = df['step'].astype('int64')

    df = df.drop(columns=['nameOrig', 'nameDest', 'isFlaggedFraud', 'step'])
    df = cudf.get_dummies(df, columns=['type'])

    feature_cols = [col for col in df.columns if col != 'isFraud']
    features_df = df[feature_cols]
    labels_df = df['isFraud']

    print(f"Feature columns (in order): {feature_cols}")

    features_tensor = torch.as_tensor(features_df.to_cupy(), device='cuda', dtype=torch.float32)
    labels_tensor = torch.as_tensor(labels_df.to_cupy(), device='cuda', dtype=torch.long)
    step_tensor = torch.as_tensor(step_series.to_cupy(), device='cuda', dtype=torch.long)

    fraud_rate = labels_tensor.float().mean().item()
    print(f"Loaded {features_tensor.shape[0]} rows, {features_tensor.shape[1]} features, "
          f"fraud rate {fraud_rate:.4%}, step range [{step_tensor.min().item()}, {step_tensor.max().item()}]")

    return features_tensor, labels_tensor, step_tensor, feature_cols


